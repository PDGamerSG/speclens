  const claim = await page.request.patch(`/api/workspace/pilot/reviews/${review.id}`, { data: { version: review.version, status: 'claimed' } })
  expect(claim.ok()).toBe(true)
  await page.getByRole('button', { name: 'Refresh factory workspace', exact: true }).click()
  await expect(page.getByText('Workspace refreshed.', { exact: true })).toBeVisible()
  await expect(page.getByLabel('Decision reason', { exact: true })).toHaveValue('Local disposition draft must not overwrite a new claim.')
  await page.getByRole('button', { name: 'Record disposition', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText(/changed|reload|conflict/i)
  const saved = await (await page.request.get('/api/workspace/pilot/overview')).json()
  expect(saved.reviews[0].status).toBe('claimed')
  expect(saved.reviews[0].outcome).toBeNull()
