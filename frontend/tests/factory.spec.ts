test('an earlier open review stays unresolved after a newer view is accepted', async ({ page }) => {
  test.setTimeout(60_000)
  await createTeam(page)
  await createLot(page)
  const overview = await (await page.request.get('/api/workspace/pilot/overview')).json()
  const lot = overview.lots[0]
  const product = overview.products[0]
  const revision = overview.revisions[0]
  const context = { factory: product.factory, part_family: product.name, spec_text: revision.spec_text, revision_id: revision.id, lot_id: lot.id, station_id: lot.station_id, physical_part_id: 'OPEN-EARLIER', sample_id: 'white-print', memory_enabled: 'false' }
  const first = await page.request.post('/api/workspace/inspect', { multipart: { ...context, capture_id: `capture-${unique()}` } })
  expect(first.ok()).toBe(true)
  const firstInspection = await first.json()
  const second = await page.request.post('/api/workspace/inspect', { multipart: { ...context, capture_id: `capture-${unique()}` } })
  expect(second.ok()).toBe(true)
  const secondInspection = await second.json()
  const refreshed = await (await page.request.get('/api/workspace/pilot/overview')).json()
  const secondReview = refreshed.reviews.find((review: { inspection_id: string }) => review.inspection_id === secondInspection.id)
  const decision = await page.request.patch(`/api/workspace/pilot/reviews/${secondReview.id}`, { data: { version: secondReview.version, status: 'closed', outcome: 'accept', reason: 'This second view is accepted after checking.' } })
  expect(decision.ok()).toBe(true)
  await page.getByRole('button', { name: 'Review', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Open review', exact: true })).toHaveCount(1)
  await page.getByRole('button', { name: 'Open review', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Record disposition', exact: true })).toBeVisible()
  const firstReview = refreshed.reviews.find((review: { inspection_id: string }) => review.inspection_id === firstInspection.id)
  await expect(page.locator('.pilot-meta').filter({ hasText: firstReview.id })).toBeVisible()
  await page.getByRole('button', { name: 'Lots', exact: true }).click()
  await expect(page.getByText('Unresolved reviews', { exact: true }).locator('..')).toContainText('1')
})

