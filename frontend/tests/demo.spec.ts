import { expect, test } from '@playwright/test'
import { readFile } from 'node:fs/promises'

test('public demo has populated sections, honest sample labels and complete downloadable evidence', async ({ page }) => {
  test.setTimeout(60_000)
  await page.goto('/')
  await page.getByRole('button', { name: 'Factory workspace', exact: true }).click()
  await expect(page.getByLabel('Demo login credentials')).toContainText('lot histories')
  await page.getByLabel('Username', { exact: true }).fill('demo.speclens')
  await page.getByLabel('Password', { exact: true }).fill('SpecLensDemo2026!')
  await page.getByRole('button', { name: 'Sign in to workspace', exact: true }).click()
  await expect(page.getByLabel('Demo workspace notice')).toContainText('186 captures')
  await expect(page.locator('.pilot-product-tab')).toHaveCount(6)
  await expect(page.locator('.pilot-revision')).toHaveCount(3)
  await page.getByRole('button', { name: 'Capture stations', exact: true }).click()
  await expect(page.locator('.pilot-list-item')).toHaveCount(12)
  await page.getByRole('button', { name: 'Lots', exact: true }).click()
  await expect(page.locator('.pilot-list-item')).toHaveCount(18)
  await page.locator('.pilot-list-item').filter({ has: page.getByRole('heading', { name: 'DEMO-PCB-01', exact: true }) }).getByRole('button', { name: 'Open lot details', exact: true }).click()
  const exported = page.waitForEvent('download')
  await page.getByRole('link', { name: 'Export lot JSON', exact: true }).click()
  const report = JSON.parse(await readFile((await (await exported).path())!, 'utf8'))
  expect(report.counts).toMatchObject({ physical_parts: 10, capture_attempts: 11, unresolved_parts: 0, missing_evidence: 0 })
  expect(report.inspections.every((item: { demo_seed: string }) => !!item.demo_seed)).toBe(true)
  await page.getByRole('button', { name: 'Capture', exact: true }).click()
  await expect(page.getByLabel('Capture lot', { exact: true }).locator('option')).toHaveCount(12)
  await page.getByRole('button', { name: 'Review', exact: true }).click()
  await expect(page.locator('.pilot-list-item').first()).toBeVisible()
  await page.getByRole('button', { name: 'Open review', exact: true }).first().click()
  await expect(page.getByRole('heading', { name: 'Illustrative recommendation', exact: true })).toBeVisible()
  await expect(page.getByText('Staged outcome / no inference', { exact: true })).toBeVisible()
  const image = page.locator('.part-image')
  await expect(image).toBeVisible()
  await expect.poll(() => image.evaluate((element: HTMLImageElement) => element.naturalWidth)).toBeGreaterThan(0)
  await page.getByRole('button', { name: 'Standards', exact: true }).click()
  await expect(page.locator('.pilot-standard')).toHaveCount(24)
  await expect(page.getByRole('button', { name: 'Retry memory sync', exact: true })).toHaveCount(0)
  await expect(page.getByText('Illustrative standard.', { exact: false }).first()).toBeVisible()
  await page.getByRole('button', { name: 'Validation', exact: true }).click()
  await expect(page.getByLabel('Validation run', { exact: true }).locator('option')).toHaveCount(4)
  await expect(page.locator('.pilot-validation-result')).toContainText('No model was run')
  await expect(page.locator('.pilot-validation-result .pilot-totals')).toContainText('240')
  await page.getByRole('button', { name: 'Nonconformances', exact: true }).click()
  await expect(page.locator('.pilot-list-item')).toHaveCount(18)
  await page.getByRole('button', { name: 'Activity', exact: true }).click()
  await expect(page.locator('.pilot-activity-item').first()).toBeVisible()
  await page.setViewportSize({ width: 390, height: 844 })
  await page.getByRole('button', { name: 'Products & specs', exact: true }).click()
  await expect(page.locator('.pilot-product-tab').first()).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await expect(page.getByRole('alert')).toHaveCount(0)
})
